def selftest():
    strata = np.array([0, 0, 0, 0, 1, 1, 1, 1]); cond = np.array([1, 1, 0, 0, 1, 0, 0, 0], dtype=bool); net = np.array([1.0, 3.0, 0.0, 2.0, 10.0, 4.0, 6.0, 5.0])
    # stratum 0: m_a 2, m_b 1, w = 2*2/4 = 1; stratum 1: m_a 10, m_b 5, w = 1*3/4 = 0.75 -> (1*1 + 0.75*5) / 1.75 = 2.7142857
    assert abs(strat_diff(strata, cond, net) - (1 + 3.75) / 1.75) < 1e-12
    # equals the OLS coefficient with stratum fixed effects
    X = np.column_stack([cond.astype(float), (strata == 0).astype(float), (strata == 1).astype(float)]); beta = np.linalg.lstsq(X, net, rcond=None)[0]
    assert abs(beta[0] - strat_diff(strata, cond, net)) < 1e-9
    assert np.isnan(strat_diff(np.array([0, 0, 1, 1]), np.array([1, 1, 1, 1], dtype=bool), np.arange(4.0)))
    p, lo, hi, pct, n = tail_p(np.array([0.0]), np.array([[-1.0], [1.0], [2.0]])); assert abs(p[0] - 1.0) < 1e-12 and abs(pct[0] - 100 / 3) < 1e-9
    p, *_ = tail_p(np.array([5.0]), np.array([[-1.0], [1.0], [2.0]])); assert abs(p[0] - 2 * (1 / 4)) < 1e-12
    assert np.allclose(holm([0.01, 0.04, 0.03]), [0.03, 0.06, 0.06]); assert np.isnan(holm([0.01, np.nan])[1]) and holm([0.01, np.nan])[0] == 0.01
    net_ = np.array([-1000.0, -2500.0, 3000.0, -1500.0, -1200.0, 500.0, -900.0]); stop_ = np.array([0, 1, 0, 1, 1, 0, 0], dtype=bool)
    assert HB_CODE["13"] == 5 and HB_CODE["<09:25"] == 0
    St = stream_frame(np.array([0, 0, 0, 0, 1, 1, 1]), np.array([2, 2, 4, 5, 3, 5, 7], dtype=np.int8), net_, stop_, np.array([5, 3, 60, 4, 4, 40, 3]))
    assert np.allclose(St["today_net"], [0, -1000, -3500, -500, 0, -1200, -700]) and (St["today_stops"] == [0, 0, 1, 1, 0, 1, 1]).all()
    runmin = SS.running_min_by_session(St["today_net"], St["sess_first"], St["sess_run"])
    # hour-conditioned k = 1: the rule binds only from hour_bin "13" (code 5): position 2 (code 4 = "12", stopped) is kept, position 3 (code 5) skipped, 5 and 6 skipped
    assert (cell_keep(dict(max_stops_today=1, max_loss_today_inr=None, rearm_after_win=False, active_from_hour_bin="13"), St, runmin) == [1, 1, 1, 0, 1, 0, 0]).all()
    assert (cell_keep(dict(max_stops_today=1, max_loss_today_inr=None, rearm_after_win=False), St, runmin) == SS.grid_keep(St["today_stops"], runmin, 1, None)).all()
    m = mechanism(St); assert m["units"] == 7 and m["p_follow_given_win"] == 1.0 and abs(m["p_follow_given_loss"] - 0.6) < 1e-12 and m["sess_multi_last_win_rate"] == 0.0
    r = n1_on_frame(St, np.random.default_rng(0), 20); assert r["observed"].shape == (7,)
    print("selftest ok")


