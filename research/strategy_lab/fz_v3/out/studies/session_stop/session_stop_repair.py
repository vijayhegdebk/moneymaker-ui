def tail_p(obs, dist):
    """Doubled-tail p of obs (vector) against dist (draws x tests), +1 corrected; also the two tails and obs's percentile."""
    obs = np.asarray(obs, dtype=float); dist = np.asarray(dist, dtype=float)
    valid = np.isfinite(dist) & np.isfinite(obs)[None, :]; n = valid.sum(axis=0)
    with np.errstate(invalid="ignore"):
        lo = (1 + ((dist <= obs[None, :] + 1e-12) & valid).sum(axis=0)) / (1 + n)
        hi = (1 + ((dist >= obs[None, :] - 1e-12) & valid).sum(axis=0)) / (1 + n)
        pct = 100.0 * (((dist < obs[None, :] - 1e-12) & valid).sum(axis=0) + 0.5 * ((np.abs(dist - obs[None, :]) <= 1e-12) & valid).sum(axis=0)) / np.maximum(n, 1)
    p = np.minimum(1.0, 2 * np.minimum(lo, hi))
    p = np.where(np.isfinite(obs) & (n > 0), p, np.nan)
    return p, lo, hi, pct, n


# ---------------------------------------------------------------- the stratified (hindsight-free) statistics
def strat_diff(strata, cond, net):
    """OLS coefficient of net on cond with stratum fixed effects = sum_h w_h (m_a,h - m_b,h) / sum_h w_h, w_h = n_a n_b / (n_a + n_b)."""
    cond = np.asarray(cond, dtype=bool); ns = int(strata.max()) + 1
    na = np.bincount(strata, weights=cond.astype(float), minlength=ns); nb = np.bincount(strata, minlength=ns) - na
    sa = np.bincount(strata, weights=net * cond, minlength=ns); sb = np.bincount(strata, weights=net * (~cond), minlength=ns)
    ok = (na > 0) & (nb > 0)
    if not ok.any(): return np.nan
    w = na[ok] * nb[ok] / (na[ok] + nb[ok])
    return float(np.sum(w * (sa[ok] / na[ok] - sb[ok] / nb[ok])) / w.sum())


def partial_spearman(strata, x, y):
    """Pearson correlation of the within-stratum demeaned ranks of x and y (ranks over the whole sample)."""
    rx, ry = sst.rankdata(x), sst.rankdata(y); ns = int(strata.max()) + 1
    cnt = np.maximum(np.bincount(strata, minlength=ns), 1)
    rx = rx - (np.bincount(strata, weights=rx, minlength=ns) / cnt)[strata]
    ry = ry - (np.bincount(strata, weights=ry, minlength=ns) / cnt)[strata]
    if rx.std() == 0 or ry.std() == 0: return np.nan
    return float(np.corrcoef(rx, ry)[0, 1])


def strat7(strata, today_net, today_stops, net):
    out = np.full(7, np.nan)
    out[0] = partial_spearman(strata, today_net, net)
    for j, k in enumerate(K_TESTS): out[1 + j] = strat_diff(strata, today_stops >= k, net)
    for j, L in enumerate(L_TESTS): out[4 + j] = strat_diff(strata, today_net <= L, net)
    return out


def holm(p):
    p = np.asarray(p, dtype=float); m = int(np.isfinite(p).sum()); adj = np.full(len(p), np.nan)
    order = [i for i in np.argsort(np.where(np.isfinite(p), p, np.inf)) if np.isfinite(p[i])]; run = 0.0
    for rank, i in enumerate(order):
        run = max(run, min(1.0, (m - rank) * p[i])); adj[i] = run
    return adj


# ---------------------------------------------------------------- frames: the real book and the memoryless streams
def stream_frame(sess, hbc, net, stop, dur, fine=None):
    """A unit sequence (time-ordered, sessions contiguous) as the arrays the statistics read; the ledger recomputed causally."""
    new_sess = np.r_[True, sess[1:] != sess[:-1]]; sess_run = np.cumsum(new_sess) - 1
    new_cell = new_sess | np.r_[True, hbc[1:] != hbc[:-1]]; cell_run = np.cumsum(new_cell) - 1
    sess_first = np.flatnonzero(new_sess)
    tn, ts = SS.recompute_ledger(net, stop, sess_first, sess_run)
    return dict(sess=sess, hbc=hbc, hour_bin=np.array(HOUR_ORDER, dtype=object)[hbc], net=net, stop=stop, dur=dur, today_net=tn, today_stops=ts,
                sess_run=sess_run, cell_run=cell_run, sess_first=sess_first, win=net > 0, fine=fine if fine is not None else hbc.astype(int))


def real_frame(T, rows, S, G):
    """The real IS units as a stream frame (the built ledger, asserted equal to the recomputed one by SS.session_frame)."""
    pre = "l1_" if T.label == "L1" else "fnd_"
    exit_ = T.F.iloc[rows][pre + "exit_i"].to_numpy().astype(int); dur = exit_ - T.setup_i[rows]
    hbc = np.array([HB_CODE[h] for h in S["hour_bin"]], dtype=np.int8)
    St = stream_frame(S["sess"], hbc, S["net"], S["stop"], dur, fine=G["fine_of_bar"][T.setup_i[rows]] if G else None)
    assert np.abs(St["today_net"] - S["today_net"]).max() < 1e-6 and (St["today_stops"] == S["today_stops"]).all()
    return St


def build_generator(T, tf, rows, S):
    F = T.F.iloc[rows]
    B = pd.read_parquet(os.path.join(H.DATA, tf, "bars.parquet"), columns=["i", "datetime", "session_idx"])
    bi = B.i.to_numpy(); assert (bi == np.arange(len(B))).all(), "bar index must be the row index"
    hhmm = B.datetime.astype(str).str[11:16].to_numpy()
    uniq = sorted(set(hhmm.tolist())); code_of = {h: HB_CODE[hbin(h)] for h in uniq}; fine_of = {h: fine_code(h) for h in uniq}
    bar_hbc = np.array([code_of[h] for h in hhmm], dtype=np.int8); fine_of_bar = np.array([fine_of[h] for h in hhmm], dtype=np.int16)
    setup = T.setup_i[rows]
    assert (bar_hbc[setup] == np.array([HB_CODE[h] for h in S["hour_bin"]])).all(), "hour_bin must be the build's clock, bar by bar"
    bs = B.session_idx.to_numpy()
    last_bar = pd.Series(bi).groupby(bs).last(); at1525 = hhmm == "15:25"
    cut = pd.Series(bi[at1525]).groupby(bs[at1525]).first().reindex(last_bar.index)
    cut = cut.fillna(last_bar).astype(int)
    exit_ = F.l1_exit_i.to_numpy().astype(int); dur = exit_ - setup; assert (dur >= 1).all()
    sess = S["sess"]; active = np.array(sorted(set(sess.tolist())))
    first = pd.Series(setup).groupby(sess).min().reindex(active).to_numpy().astype(int)
    nxt_same = np.r_[sess[1:] == sess[:-1], False]
    gaps = (np.r_[setup[1:], 0] - exit_)[nxt_same]; assert (gaps >= 1).all(), "the next SETUP always follows the exit"
    hbc = bar_hbc[setup]
    pools = [np.flatnonzero(hbc == c) for c in range(len(HOUR_ORDER))]
    return dict(tf=tf, bar_hbc=bar_hbc, fine_of_bar=fine_of_bar, cut=cut.reindex(active).to_numpy().astype(int), first=first, active=active,
                net=S["net"].astype(float), stop=S["stop"].astype(bool), dur=dur.astype(int), gaps=gaps.astype(int), pools=pools, n_real=int(len(rows)),
                pool_sizes=[int(len(p)) for p in pools], gap_median=float(np.median(gaps)), sessions_without_1525=int(cut.isna().sum()) if hasattr(cut, "isna") else 0)


def simulate(G, seed, tied=True):
    """One memoryless stream on the real session skeleton (see the docstring)."""
    rng = np.random.default_rng(seed)
    n_max = 8 * G["n_real"]; U = rng.random((3, n_max)); q = 0
    S_, Hc, J, Dd, Fi = [], [], [], [], []
    bar_hbc, pools, dur, gaps, fine_of_bar = G["bar_hbc"], G["pools"], G["dur"], G["gaps"], G["fine_of_bar"]
    ng = len(gaps)
    for s, t, c in zip(G["active"], G["first"], G["cut"]):
        t = int(t); c = int(c)
        while t < c:
            h = int(bar_hbc[t]); p = pools[h]
            if len(p) == 0: t += 1; continue
            if q >= n_max: raise RuntimeError("stream longer than 8x the real book")
            j = p[int(U[0, q] * len(p))]
            d = int(dur[j]) if tied else int(dur[p[int(U[1, q] * len(p))]])
            S_.append(s); Hc.append(h); J.append(j); Dd.append(d); Fi.append(int(fine_of_bar[t]))
            ex = min(t + max(d, 1), c)
            t = ex + int(gaps[int(U[2, q] * ng)])
            q += 1
    J = np.array(J, dtype=int)
    return stream_frame(np.array(S_, dtype=int), np.array(Hc, dtype=np.int8), G["net"][J], G["stop"][J], np.array(Dd, dtype=int), fine=np.array(Fi, dtype=np.int16))


