def cell_stats(St, cells):
    runmin = SS.running_min_by_session(St["today_net"], St["sess_first"], St["sess_run"])
    pooled, strat, share = np.full(len(cells), np.nan), np.full(len(cells), np.nan), np.full(len(cells), np.nan)
